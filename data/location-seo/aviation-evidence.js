export function validateAviationEvidence(records, geographicRecords) {
  if (!Array.isArray(records)) return ['Aviation evidence must be an array.'];
  if (!Array.isArray(geographicRecords)) return ['Geographic records must be an array.'];
  const errors = [];
  const ids = new Set();
  const geography = new Map(geographicRecords.map((record) => [record.id, record]));
  for (const [index, record] of records.entries()) {
    const label = record?.id || `index ${index}`;
    if (!record || typeof record !== 'object' || Array.isArray(record)) {
      errors.push(`Aviation evidence "${label}" must be an object.`);
      continue;
    }
    if (!record.id || ids.has(record.id)) errors.push(`Aviation evidence "${label}" has a missing or duplicate ID.`);
    ids.add(record.id);
    for (const key of ['name', 'type', 'country', 'countryCode', 'source', 'sourceUrl', 'verificationStatus']) {
      if (typeof record[key] !== 'string' || !record[key].trim()) {
        errors.push(`Aviation evidence "${label}" needs ${key}.`);
      }
    }
    if (!AVIATION_EVIDENCE_TYPES.includes(record.type)) {
      errors.push(`Aviation evidence "${label}" has an unsupported type.`);
    }
    if (!geography.has(record.locationId)) {
      errors.push(`Aviation evidence "${label}" references an unknown geographic location.`);
    } else {
      const location = geography.get(record.locationId);
      if (location.countryCode !== record.countryCode || location.country !== record.country) {
        errors.push(`Aviation evidence "${label}" country does not match its geographic location.`);
      }
    }
    if (!['located-within', 'regional-context'].includes(record.geographicRelationship)) {
      errors.push(`Aviation evidence "${label}" has an invalid geographic relationship.`);
    }
    if (record.geographicRelationship === 'regional-context'
      && (!Array.isArray(record.relatedLocationIds) || record.relatedLocationIds.length === 0)) {
      errors.push(`Regional aviation evidence "${label}" needs explicit related location IDs.`);
    }
    if ((record.relatedLocationIds || []).some((id) => !geography.has(id))) {
      errors.push(`Aviation evidence "${label}" references an unknown related location.`);
    }
    if (!/^https:\/\//.test(record.sourceUrl)) {
      errors.push(`Aviation evidence "${label}" needs an HTTPS source URL.`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(record.verifiedAt || '')) {
      errors.push(`Aviation evidence "${label}" needs a dated verification status.`);
    }
    if (record.sourceDate !== null && record.sourceDate !== undefined
      && !/^\d{4}-\d{2}-\d{2}$/.test(record.sourceDate)) {
      errors.push(`Aviation evidence "${label}" has an invalid source date.`);
    }
    if (!Array.isArray(record.supportingSourceUrls)
      || record.supportingSourceUrls.some((url) => !/^https:\/\//.test(url))) {
      errors.push(`Aviation evidence "${label}" has invalid supporting sources.`);
    }
    if (!record.regulatoryAuthority) {
      errors.push(`Aviation evidence "${label}" needs a regulatory authority.`);
    }
  }
  return errors;
}
