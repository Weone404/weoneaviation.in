const VERIFIED_AT = '2026-10-03';

function evidence({
  id,
  name,
  type,
  locationId,
  country,
  countryCode,
  sourceName,
  sourceUrl,
  sourceDate = null,
  authority,
  note,
  supportingSourceUrls = [],
  fact,
  geographicRelationship = 'located-within',
  relatedLocationIds = [],
}) {
  return Object.freeze({
    id,
    name,
    type,
    locationId,
    geographicRelationship,
    relatedLocationIds,
    country,
    countryCode,
    source: sourceName,
    sourceUrl,
    sourceDate,
    verifiedAt: VERIFIED_AT,
    verificationStatus: 'primary-source-listed',
    regulatoryAuthority: authority,
    attributionNote: note,
    ...(fact ? { fact } : {}),
    supportingSourceUrls,
  });
}

