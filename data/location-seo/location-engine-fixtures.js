function node({
  id,
  slug,
  name,
  type,
  parentId,
  country,
  state,
  city,
  county,
  locality,
  postalCode,
  aliases = [],
  relationship,
  regulatoryContext,
  verifiedFacts = [],
  indexabilityReview,
  sourceLinks = [],
}) {
  const record = {
    id,
    slug,
    name,
    type,
    parentId: parentId || null,
    country: country || null,
    state: state || null,
    city: city || (type === 'city' ? name : null),
    county: county || null,
    locality: locality || (['locality', 'neighborhood'].includes(type) ? name : null),
    postalCode: postalCode || null,
    aliases,
    testOnly: true,
    relationship: relationship || null,
    renderable: true,
    indexable: false,
    verifiedFacts,
    supportedServices: serviceDefinitions.map(({ slug: serviceSlug }) => serviceSlug),
    serviceContent: {},
    regulatoryContext: regulatoryContext || null,
    authorityPath: '/pilot-training-in-india',
    authorityLabel: 'Aviation training guidance',
    localSections: [],
    sourceLinks,
    localFAQs: [],
    physicalAcademy: false,
    onlineTraining: relationship === 'ONLINE',
    flightTrainingGuidance: false,
    ...(indexabilityReview ? { indexabilityReview } : {}),
  };
  record.regulatoryContextName = regulatoryContext?.authority
    || regulatorByCountry[country]
    || 'the applicable aviation regulator';
  record.serviceContent = fixtureServiceContent(record);
  return record;
}

