const reviewedAt = '2026-10-03';
const COUNTRY_CODES = {
  India: 'IN',
  'United States': 'US',
  'United Kingdom': 'GB',
  Canada: 'CA',
  Australia: 'AU',
};

function source(href, publisher, title, scope, license = null) {
  return { href, publisher, title, scope, reviewedAt, license };
}

function place({
  id,
  slug,
  name,
  type,
  parentId = null,
  country,
  aliases = [],
  sourceLinks = [],
  relatedLocationIds = [],
  postalCodes = [],
  latitude = null,
  longitude = null,
  status = 'verified',
}) {
  const primarySource = sourceLinks[0];
  return {
    id,
    slug,
    name,
    canonicalName: name,
    type,
    parentId,
    parentIds: [],
    country,
    countryCode: COUNTRY_CODES[country],
    aliases,
    postalCodes,
    latitude,
    longitude,
    source: primarySource?.publisher || null,
    sourceUrl: primarySource?.href || null,
    sourceDate: primarySource?.sourceDate || null,
    status,
    sourceLinks,
    relatedLocationIds,
  };
}

