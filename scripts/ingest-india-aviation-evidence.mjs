import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AVIATION_EVIDENCE_RECORDS } from '../data/location-seo/aviation-evidence.js';
import {
  DGCA_FTO_ROSTER_BASES,
  DGCA_FTO_ROSTER_SOURCE,
} from '../data/location-seo/dgca-fto-roster.js';
import { GLOBAL_GEOGRAPHIC_PILOT } from '../data/location-seo/geography/global-pilot.js';
import { normalizeIndiaAviationEvidence } from '../lib/indiaAviationEvidenceIngestion.js';
import { resolveIndiaGeographicLocation } from '../lib/indiaGeographicRegistry.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PILOT_TRAINING_EVIDENCE_TYPES = new Set([
  'flight-school',
  'flying-club',
  'aviation-college',
  'aviation-academy',
  'pilot-training-organization',
  'airline-training-organization',
]);
const GENERATED_PATH = path.join(
  ROOT,
  'data',
  'location-seo',
  'india-aviation-evidence.generated.js',
);
const REPORT_PATH = path.join(
  ROOT,
  'data',
  'location-seo',
  'geography',
  'india-aviation-evidence-coverage-report.json',
);
const REVIEWED_AT = '2026-10-08';

function normalize(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, ' ');
}

function identity(location) {
  return [
    location.countryCode,
    normalize(location.state),
    normalize(location.type),
    normalize(location.canonicalName || location.name),
  ].join('|');
}

function sourceHierarchy(record, recordsById) {
  const hierarchy = [];
  const seen = new Set();
  let current = record;
  while (current && !seen.has(current.id)) {
    seen.add(current.id);
    hierarchy.unshift(current);
    current = current.parentId ? recordsById.get(current.parentId) : null;
  }
  return hierarchy;
}

async function existingIndiaEvidence() {
  const recordsById = new Map(GLOBAL_GEOGRAPHIC_PILOT.records.map((record) => [
    record.id,
    record,
  ]));
  const result = [];
  for (const evidence of AVIATION_EVIDENCE_RECORDS) {
    if (evidence.countryCode !== 'IN' || evidence.type === 'aviation-authority') continue;
    const sourceLocation = recordsById.get(evidence.locationId);
    if (!sourceLocation) continue;
    const hierarchy = sourceHierarchy(sourceLocation, recordsById);
    const state = hierarchy.find(({ type }) => ['state', 'region'].includes(type));
    const types = [sourceLocation.type, 'city', 'town', 'populated-place']
      .filter((type, index, all) => all.indexOf(type) === index);
    for (const type of types) {
      try {
        const resolved = await resolveIndiaGeographicLocation(sourceLocation.name, {
          type,
          ...(state ? { state: state.name } : {}),
        });
        if (resolved.location
          && normalize(resolved.location.name) === normalize(sourceLocation.name)
          && resolved.location.type === type) {
          result.push({ ...evidence, locationId: resolved.location.id });
          break;
        }
      } catch (error) {
        if (!/is ambiguous/i.test(error.message)) throw error;
      }
    }
  }
  return result;
}

function getIndiaLocationForEvidence(evidence) {
  const sourceLocation = GLOBAL_GEOGRAPHIC_PILOT.records.find((record) => (
    record.id === evidence.locationId
  ));
  if (!sourceLocation) return null;
  const hierarchy = sourceHierarchy(
    sourceLocation,
    new Map(GLOBAL_GEOGRAPHIC_PILOT.records.map((record) => [record.id, record])),
  );
  const state = hierarchy.find(({ type }) => ['state', 'region'].includes(type));
  return {
    countryCode: 'IN',
    state: state?.name || sourceLocation.state || null,
    type: sourceLocation.type,
    name: sourceLocation.canonicalName || sourceLocation.name,
  };
}

function locationCounts(evidence, resolveLocationForEvidence) {
  const locations = new Map();
  for (const item of evidence) {
    const location = resolveLocationForEvidence(item);
    if (location) locations.set(identity(location), location);
  }
  return [...locations.values()];
}

function writeGeneratedModule(records) {
  return [
    '// Generated by scripts/ingest-india-aviation-evidence.mjs; do not edit by hand.',
    `export const INDIA_AVIATION_EVIDENCE_VERIFIED_AT = '${REVIEWED_AT}';`,
    'export const INDIA_AVIATION_EVIDENCE_RECORDS = Object.freeze(',
    `${JSON.stringify(records, null, 2)},`,
    ');',
    '',
  ].join('\n');
}

async function main() {
  const beforeRecords = AVIATION_EVIDENCE_RECORDS.filter((item) => (
    item.countryCode === 'IN' && item.type !== 'aviation-authority'
  ));
  const normalized = await normalizeIndiaAviationEvidence({
    resolveLocation: resolveIndiaGeographicLocation,
    existingEvidence: await existingIndiaEvidence(),
  });

  const afterEvidence = [
    ...beforeRecords,
    ...normalized.records,
  ];
  const beforePilotTrainingEvidence = beforeRecords.filter(({ type }) => (
    PILOT_TRAINING_EVIDENCE_TYPES.has(type)
  ));
  const afterPilotTrainingEvidence = afterEvidence.filter(({ type }) => (
    PILOT_TRAINING_EVIDENCE_TYPES.has(type)
  ));
  const newPilotTrainingRecords = normalized.records.filter(({ type }) => (
    PILOT_TRAINING_EVIDENCE_TYPES.has(type)
  ));
  const aviationIdentity = (item) => {
    const location = getIndiaLocationForEvidence(item);
    return identity({
      countryCode: 'IN',
      state: item.geographicState || location?.state,
      type: item.geographicType || location?.type,
      name: item.geographicName || location?.name,
    });
  };
  const beforePilotTrainingLocations = new Set(beforePilotTrainingEvidence.map(aviationIdentity));
  const afterPilotTrainingLocations = new Set(afterPilotTrainingEvidence.map(aviationIdentity));
  const newlyPilotTrainingLocations = [...afterPilotTrainingLocations]
    .filter((locationKey) => !beforePilotTrainingLocations.has(locationKey));
  const addedRecordsByType = normalized.records.reduce((counts, item) => {
    counts[item.type] = (counts[item.type] || 0) + 1;
    return counts;
  }, {});
  const globalLocation = getIndiaLocationForEvidence;
  const beforeLocations = locationCounts(beforeRecords, globalLocation);
  const afterLocations = new Map(beforeLocations.map((record) => [identity(record), record]));
  for (const record of normalized.records) {
    afterLocations.set(identity({
      countryCode: 'IN',
      state: record.geographicState,
      type: record.geographicType,
      name: record.geographicName,
    }), {
      countryCode: 'IN',
      state: record.geographicState,
      type: record.geographicType,
      name: record.geographicName,
      hierarchy: record.hierarchy,
    });
  }
  const allLocationsAfter = [...afterLocations.values()];
  const beforeLocationKeys = new Set(beforeLocations.map(identity));
  const newlyEvidenceBackedLocations = allLocationsAfter.filter((location) => (
    !beforeLocationKeys.has(identity(location))
  ));
  const directLocationsBefore = locationCounts(
    beforeRecords.filter(({ geographicRelationship }) => (
      geographicRelationship !== 'regional-context'
    )),
    globalLocation,
  );
  const regionalLocationsBefore = new Set(beforeRecords
    .filter(({ geographicRelationship }) => geographicRelationship === 'regional-context')
    .flatMap((item) => item.relatedLocationIds || [])
    .map((id) => GLOBAL_GEOGRAPHIC_PILOT.records.find((record) => record.id === id))
    .filter(Boolean)
    .map(identity)).size;
  const directLocationKeys = new Set(directLocationsBefore.map(identity));
  for (const record of normalized.records.filter(({ geographicRelationship }) => (
    geographicRelationship !== 'regional-context'
  ))) {
    directLocationKeys.add(identity({
      countryCode: 'IN',
      state: record.geographicState,
      type: record.geographicType,
      name: record.geographicName,
    }));
  }
  const regionalContextLocationKeys = new Set(beforeRecords
    .filter(({ geographicRelationship }) => geographicRelationship === 'regional-context')
    .flatMap((item) => item.relatedLocationIds || [])
    .map((id) => GLOBAL_GEOGRAPHIC_PILOT.records.find((record) => record.id === id))
    .filter(Boolean)
    .map(identity));
  for (const record of normalized.records.filter(({ geographicRelationship }) => (
    geographicRelationship === 'regional-context'
  ))) {
    regionalContextLocationKeys.add(identity({
      countryCode: 'IN',
      state: record.geographicState,
      type: record.geographicType,
      name: record.geographicName,
    }));
  }
  const sourceDomains = (items) => [...new Set(items.map(({ sourceUrl }) => (
    new URL(sourceUrl).hostname
  )))].sort();
  const locationNames = allLocationsAfter.map((location) => ({
    name: location.name || location.canonicalName,
    type: location.type,
    state: location.state,
  }));
  const statesBefore = [...new Set(beforeLocations.map(({ state }) => state).filter(Boolean))].sort();
  const statesAfter = [...new Set(allLocationsAfter.map(({ state }) => state).filter(Boolean))].sort();
  const districtOrCityTypes = new Set(['district', 'city', 'town', 'populated-place']);
  const districtsOrCitiesBefore = beforeLocations.filter(({ type }) => districtOrCityTypes.has(type));
  const districtsOrCitiesAfter = allLocationsAfter.filter(({ type }) => districtOrCityTypes.has(type));

  fs.writeFileSync(GENERATED_PATH, writeGeneratedModule(normalized.records), 'utf8');

  const report = {
    schemaVersion: 1,
    phase: '4G',
    reviewedAt: REVIEWED_AT,
    scope: 'India only; existing DGCA medical lists plus source-listed bases from the DGCA approved-FTO roster dated 3 October 2026.',
    ingestion: {
      method: 'Exact source-listed place name + optional explicit geographic level and state are resolved against the India geographic registry. Explicitly conflicting/unresolved source entries are retained as ambiguous or unmatched; a record is emitted only after exact location, country, state, and hierarchy validation.',
      sourceRows: normalized.sourceRecordCount,
      emittedRecords: normalized.records.length,
      emittedRecordsByType: addedRecordsByType,
      newlyAddedPilotTrainingRecords: newPilotTrainingRecords.length,
      newlyAddedAirportOrAerodromeRecords: normalized.records.filter(({ type }) => (
        type === 'airport' || type === 'aerodrome'
      )).length,
      newlyCoveredPilotTrainingLocations: newlyPilotTrainingLocations.length,
      pilotTrainingSource: {
        publisher: DGCA_FTO_ROSTER_SOURCE.publisher,
        title: DGCA_FTO_ROSTER_SOURCE.title,
        sourceDate: DGCA_FTO_ROSTER_SOURCE.sourceDate,
        sourceDateBasis: DGCA_FTO_ROSTER_SOURCE.sourceDateBasis,
        pdfCreatedAt: DGCA_FTO_ROSTER_SOURCE.pdfCreatedAt,
        objectLastModifiedAt: DGCA_FTO_ROSTER_SOURCE.objectLastModifiedAt,
        verificationDate: DGCA_FTO_ROSTER_SOURCE.verificationDate,
        url: DGCA_FTO_ROSTER_SOURCE.url,
        sourceRows: DGCA_FTO_ROSTER_BASES.reduce(
          (total, organization) => total + organization.bases.length,
          0,
        ),
      },
      unmatchedEvidence: normalized.unmatched,
      ambiguousEvidence: normalized.ambiguous,
      duplicateEvidence: normalized.duplicates,
      invalidGeographicMappings: normalized.invalidMappings,
      regionalContextPolicy: 'A record is labeled regional-context where the source lists a separately named base or only supports regional association. Descendant routes also receive inherited evidence as regional-context. No unverified nearby or state-wide relationships are added.',
    },
    coverage: {
      before: {
        evidenceRecords: beforeRecords.length,
        pilotTrainingEvidenceRecords: beforePilotTrainingEvidence.length,
        airportOrAerodromeEvidenceRecords: beforeRecords.filter(({ type }) => (
          type === 'airport' || type === 'aerodrome'
        )).length,
        directEvidenceRecords: beforeRecords.filter(({ geographicRelationship }) => (
          geographicRelationship !== 'regional-context'
        )).length,
        regionalEvidenceRecords: beforeRecords.filter(({ geographicRelationship }) => (
          geographicRelationship === 'regional-context'
        )).length,
        uniqueGeographicLocations: beforeLocations.length,
        states: statesBefore,
        stateCount: statesBefore.length,
        districtsOrCities: districtsOrCitiesBefore.map(({ name, type, state }) => ({
          name: name || 'unknown',
          type,
          state,
        })),
        districtsOrCitiesCount: districtsOrCitiesBefore.length,
        directEvidenceLocations: directLocationsBefore.length,
        regionalContextLocations: regionalLocationsBefore,
        evidenceTypes: [...new Set(beforeRecords.map(({ type }) => type))].sort(),
        sourceDomains: sourceDomains(beforeRecords),
      },
      after: {
        evidenceRecords: afterEvidence.length,
        newlyAddedEvidenceRecords: normalized.records.length,
        newlyAddedEvidenceRecordsByType: addedRecordsByType,
        pilotTrainingEvidenceRecords: afterPilotTrainingEvidence.length,
        newlyAddedPilotTrainingEvidenceRecords: newPilotTrainingRecords.length,
        newlyCoveredPilotTrainingLocations: newlyPilotTrainingLocations.length,
        airportOrAerodromeEvidenceRecords: afterEvidence.filter(({ type }) => (
          type === 'airport' || type === 'aerodrome'
        )).length,
        directEvidenceRecords: afterEvidence.filter(({ geographicRelationship }) => (
          geographicRelationship !== 'regional-context'
        )).length,
        regionalEvidenceRecords: afterEvidence.filter(({ geographicRelationship }) => (
          geographicRelationship === 'regional-context'
        )).length,
        uniqueGeographicLocations: allLocationsAfter.length,
        newlyEvidenceBackedLocations: newlyEvidenceBackedLocations.length,
        newlyEvidenceBackedLocationDetails: newlyEvidenceBackedLocations.map((location) => ({
          name: location.name || location.canonicalName,
          type: location.type,
          state: location.state,
          geography: location.hierarchy || null,
        })),
        states: statesAfter,
        stateCount: statesAfter.length,
        districtsOrCities: districtsOrCitiesAfter.map(({ name, type, state }) => ({
          name: name || 'unknown',
          type,
          state,
        })),
        districtsOrCitiesCount: districtsOrCitiesAfter.length,
        directEvidenceLocations: directLocationKeys.size,
        regionalContextLocations: regionalContextLocationKeys.size,
        evidenceTypes: [...new Set(afterEvidence.map(({ type }) => type))].sort(),
        sourceDomains: sourceDomains(afterEvidence),
      },
    },
    addedRecords: normalized.records.map((record) => ({
      id: record.id,
      name: record.name,
      type: record.type,
      locationId: record.locationId,
      geography: record.hierarchy,
      relationship: record.geographicRelationship,
      source: record.source,
      sourceUrl: record.sourceUrl,
      sourceDate: record.sourceDate,
      sourceGroup: record.attributionNote.split(';')[0],
    })),
  };
  fs.writeFileSync(REPORT_PATH, `${JSON.stringify(report, null, 2)}\n`, 'utf8');

  console.log(JSON.stringify({
    emittedRecords: normalized.records.length,
    uniqueLocationsBefore: beforeLocations.length,
    uniqueLocationsAfter: allLocationsAfter.length,
    newlyEvidenceBackedLocations: allLocationsAfter.length - beforeLocations.length,
    unmatchedEvidence: normalized.unmatched.length,
    ambiguousEvidence: normalized.ambiguous.length,
    duplicateEvidence: normalized.duplicates.length,
    invalidGeographicMappings: normalized.invalidMappings.length,
    generatedPath: path.relative(ROOT, GENERATED_PATH),
    reportPath: path.relative(ROOT, REPORT_PATH),
  }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
